-- Chat snapshots include up to 6000 UTF-8 bytes plus bounded metadata/JSON escaping.
ALTER TABLE email_outbox DROP CONSTRAINT email_outbox_payload_check;
ALTER TABLE email_outbox ADD CONSTRAINT email_outbox_payload_check CHECK(octet_length(payload::text)<=16384);
ALTER TABLE users ADD COLUMN email_reply_enabled boolean NOT NULL DEFAULT false;
ALTER TABLE order_messages ADD COLUMN sequence bigint GENERATED BY DEFAULT AS IDENTITY;
-- Preserve the chronological order of pre-existing conversations during upgrade.
WITH ordered AS (SELECT id,row_number() OVER(ORDER BY created_at,id) AS n FROM order_messages)
UPDATE order_messages m SET sequence=ordered.n FROM ordered WHERE m.id=ordered.id;
ALTER TABLE order_messages ALTER COLUMN sequence SET GENERATED ALWAYS;
ALTER TABLE order_messages ADD COLUMN origin text NOT NULL DEFAULT 'web' CHECK(origin IN ('web','email'));
CREATE UNIQUE INDEX order_messages_sequence ON order_messages(sequence);
CREATE INDEX order_messages_page ON order_messages(order_id,sequence);
CREATE TABLE chat_reads (
 order_id text NOT NULL REFERENCES orders(id),
 participant text NOT NULL CHECK(length(participant) BETWEEN 1 AND 100),
 sequence bigint NOT NULL CHECK(sequence>=0),
 PRIMARY KEY(order_id,participant)
);
CREATE TABLE chat_reply_routes (
 id text PRIMARY KEY,
 order_id text NOT NULL REFERENCES orders(id),
 user_id text REFERENCES users(id),
 email text NOT NULL CHECK(length(email) BETWEEN 3 AND 254 AND email=lower(btrim(email))),
 operator boolean NOT NULL,
 expires_at bigint NOT NULL,
 revoked_at bigint
);
CREATE INDEX chat_reply_routes_order ON chat_reply_routes(order_id);
ALTER TABLE email_outbox ADD COLUMN chat_frozen boolean NOT NULL DEFAULT false;
ALTER TABLE email_outbox ADD COLUMN chat_order text REFERENCES orders(id);
ALTER TABLE email_outbox ADD COLUMN chat_operator boolean;
ALTER TABLE email_outbox ADD COLUMN chat_first bigint;
ALTER TABLE email_outbox ADD COLUMN chat_last bigint;
ALTER TABLE email_outbox ADD COLUMN reply_route text REFERENCES chat_reply_routes(id);
CREATE INDEX email_outbox_chat_group ON email_outbox(chat_order,chat_operator,recipient) WHERE status='pending' AND attempts=0;
CREATE TABLE chat_mailboxes (
 mailbox text PRIMARY KEY CHECK(length(mailbox) BETWEEN 1 AND 128),
 uidvalidity bigint NOT NULL CHECK(uidvalidity>0),
 last_uid bigint NOT NULL CHECK(last_uid>=0),
 lease_token text,
 locked_until bigint NOT NULL DEFAULT 0
);
CREATE TABLE chat_inbound (
 mailbox text NOT NULL,
 uidvalidity bigint NOT NULL,
 uid bigint NOT NULL,
 digest bytea NOT NULL CHECK(octet_length(digest)=32),
 outcome text NOT NULL CHECK(outcome IN ('imported','duplicate','rejected','review','ignored')),
 reason text NOT NULL CHECK(reason ~ '^[a-z_]{1,40}$'),
 message_id text REFERENCES order_messages(id),
 created_at bigint NOT NULL,
 PRIMARY KEY(mailbox,uidvalidity,uid)
);
CREATE INDEX chat_inbound_digest ON chat_inbound(mailbox,digest) WHERE outcome='imported';
CREATE INDEX chat_inbound_retention ON chat_inbound(created_at);
